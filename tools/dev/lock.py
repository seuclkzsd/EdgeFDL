"""生成 requirements-lock.txt：Python 3.12、linux/amd64 的 CPU 安装所需全部包的精确版本与 SHA-256。

    python tools/dev/lock.py                  # 在 Dockerfile 固定的基础镜像里用 pip 解析（需要 Docker）
    python tools/dev/lock.py --report r.json  # 改用已有的 pip install --dry-run --report 输出

直接依赖的版本在 ROOTS 里：torch、numpy、PyYAML、psutil 取发布结果所用的版本；传递依赖由 pip 解析。
环境变量 EDGEFDL_REGISTRY 指定基础镜像的仓库前缀，PIP_INDEX_URL 指定 PyPI 镜像，HTTPS_PROXY 传入容器。
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LOCK = ROOT / "requirements-lock.txt"
TORCH_INDEX = "https://download.pytorch.org/whl/cpu"
ROOTS = ("torch==2.9.1+cpu", "numpy==2.3.3", "pyyaml==6.0.3", "psutil==7.2.2")
HEADER = """\
# SPDX-FileCopyrightText: 2026 seuclkzsd and the EdgeFDL contributors
# SPDX-License-Identifier: Apache-2.0
# Exact versions and SHA-256 hashes of everything pip installs for the CPU install of EdgeFDL on
# Python 3.12, linux/amd64. Generated by tools/dev/lock.py; do not edit by hand. The root Dockerfile
# installs this file with --require-hashes --no-deps. Licenses: docs/dependencies.md.
--extra-index-url {index}

"""


def base_image() -> str:
    """Dockerfile 是基础镜像 digest 的唯一出处。"""
    text = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    image = re.search(r"^FROM \$\{REGISTRY\}/(\S+@sha256:[0-9a-f]{64})", text, re.M).group(1)
    return os.environ.get("EDGEFDL_REGISTRY", "docker.io/library") + "/" + image


def resolve(report: Path) -> None:
    """在基础镜像里解析，写出 pip 报告；容器不留痕（--rm），以当前用户运行。"""
    env = ["-e", "HOME=/tmp", "-e", "PIP_DISABLE_PIP_VERSION_CHECK=1"]
    for k in ("PIP_INDEX_URL", "HTTP_PROXY", "HTTPS_PROXY", "NO_PROXY", "http_proxy", "https_proxy", "no_proxy"):
        if os.environ.get(k):
            env += ["-e", f"{k}={os.environ[k]}"]
    cmd = ["docker", "run", "--rm", "--network", "host", "--user", f"{os.getuid()}:{os.getgid()}",
           "-v", f"{report.parent}:/out", *env, base_image(),
           "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", f"/out/{report.name}",
           "--extra-index-url", TORCH_INDEX, *ROOTS]
    subprocess.run(cmd, check=True)


def render(report: dict) -> str:
    """pip 报告 → 锁文件文本（按包名排序，同一输入总得到同一输出）。"""
    env = report["environment"]
    if env["python_version"] != "3.12" or env["platform_machine"] != "x86_64":
        raise SystemExit(f"lock: 报告来自 Python {env['python_version']} / {env['platform_machine']}，"
                         "须为 Python 3.12 / x86_64")
    rows = []
    for item in report["install"]:
        meta = item["metadata"]
        name = re.sub(r"[-_.]+", "-", meta["name"]).lower()
        rows.append((name, meta["version"], item["download_info"]["archive_info"]["hashes"]["sha256"]))
    out = [HEADER.format(index=TORCH_INDEX)]
    out += [f"{n}=={v} \\\n    --hash=sha256:{h}\n" for n, v, h in sorted(rows)]
    return "".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description="生成 requirements-lock.txt")
    ap.add_argument("--report", help="已有的 pip 报告 JSON；缺省则在基础镜像里解析")
    ap.add_argument("-o", "--out", default=str(LOCK))
    args = ap.parse_args()
    if args.report:
        report = json.loads(Path(args.report).read_text(encoding="utf-8"))
    else:
        with tempfile.TemporaryDirectory() as d:
            path = Path(d) / "report.json"
            resolve(path)
            report = json.loads(path.read_text(encoding="utf-8"))
    text = render(report)
    Path(args.out).write_text(text, encoding="utf-8")
    print(f"lock: {text.count('--hash=')} 个包写入 {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
